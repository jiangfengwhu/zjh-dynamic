import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// The dynamic host ships JS only, without Metro's APK asset directory.
// Embed source media and materialize videos in the existing native cache.
const root = new URL("../apps/mobile/src/shell/feed/", import.meta.url);
const entries = await Promise.all(
  ["avatar.png", "working.mp4", "making.mp4", "milestone.mp4"].map(
    async (name) => {
      const bytes = await readFile(new URL(`assets/${name}`, root));
      return [
        name.split(".")[0],
        {
          hash: createHash("sha256").update(bytes).digest("hex"),
          base64: bytes.toString("base64"),
        },
      ];
    }
  )
);
await writeFile(
  new URL("pixelAssets.ts", root),
  `// Generated by scripts/embed-feed-assets.mjs; edit assets/, then regenerate.\nexport const pixelAssets = ${JSON.stringify(
    Object.fromEntries(entries)
  )} as const;\n`
);
