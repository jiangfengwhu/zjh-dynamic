import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// The avatar and application logo are embedded in the dynamic package.
const root = new URL("../apps/mobile/src/shell/feed/", import.meta.url);
const entries = await Promise.all(
  ["avatar.webp", "logo.webp"].map(async (name) => {
    const bytes = await readFile(new URL(`assets/${name}`, root));
    return [
      name.split(".")[0],
      {
        hash: createHash("sha256").update(bytes).digest("hex"),
        base64: bytes.toString("base64"),
      },
    ];
  })
);
await writeFile(
  new URL("brandAssets.ts", root),
  `// Generated by scripts/embed-feed-assets.mjs; edit assets/, then regenerate.\nexport const brandAssets = ${JSON.stringify(
    Object.fromEntries(entries)
  )} as const;\n`
);
